// Deterministic, stable, valid-shaped UUIDs derived from a namespace + the
// content's own natural key (slug or id) — not RFC 4122 v5 compliant, but
// Postgres only needs a syntactically valid UUID, and determinism is what
// lets join-table seed rows reference parent rows without a live database.
function uuidFor(namespace: string, value: string): string {
  const hex = createHash('sha256').update(`${namespace}:${value}`).digest('hex').slice(0, 32)
  const bytes = hex.split('')
  bytes[12] = '5' // version nibble
  bytes[16] = (((parseInt(bytes[16], 16) || 0) & 0x3) | 0x8).toString(16) // variant nibble
  const h = bytes.join('')
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}`
}

function str(value: string | null | undefined): string {
  if (value === null || value === undefined) return 'null'
  return `'${value.replace(/'/g, "''")}'`
}

function int(value: number | null | undefined): string {
  return value === null || value === undefined ? 'null' : String(value)
}

function textArray(values: readonly string[] | undefined): string {
  if (!values || values.length === 0) return "'{}'"
  return `ARRAY[${values.map((v) => str(v)).join(', ')}]::text[]`
}

function jsonb(value: unknown): string {
  return `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`
}

function insert(table: string, columns: string[], rows: string[][]): string {
  if (rows.length === 0) return ''
  const values = rows.map((row) => `  (${row.join(', ')})`).join(',\n')
  return `insert into ${table} (${columns.join(', ')}) values\n${values};\n`
}

