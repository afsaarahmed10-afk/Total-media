const serviceRelatedServiceRows: string[][] = []
const serviceRelatedEquipmentCategoryRows: string[][] = []
const serviceFaqRows: string[][] = []
for (const s of services) {
  s.relatedServiceSlugs.forEach((slug, i) =>
    serviceRelatedServiceRows.push([
      str(uuidFor('service', s.slug)),
      str(uuidFor('service', slug)),
      int(i),
    ]),
  )
  s.relatedEquipmentCategorySlugs.forEach((slug, i) =>
    serviceRelatedEquipmentCategoryRows.push([
      str(uuidFor('service', s.slug)),
      str(uuidFor('equipment_category', slug)),
      int(i),
    ]),
  )
  s.faqIds.forEach((faqId, i) =>
    serviceFaqRows.push([str(uuidFor('service', s.slug)), str(uuidFor('faq', faqId)), int(i)]),
  )
}
parts.push(
  insert('service_related_services', ['service_id', 'related_service_id', 'sort_order'], serviceRelatedServiceRows),
)
parts.push(
  insert(
    'service_related_equipment_categories',
    ['service_id', 'equipment_category_id', 'sort_order'],
    serviceRelatedEquipmentCategoryRows,
  ),
)
parts.push(insert('service_faqs', ['service_id', 'faq_id', 'sort_order'], serviceFaqRows))

